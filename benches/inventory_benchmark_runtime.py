"""Qualified post-run dependency inventory; never rewrites measurement metadata."""

import argparse
import datetime
import hashlib
import importlib.metadata
import json
from pathlib import Path


def inventory_distribution(name, first_measurement):
    distribution = importlib.metadata.distribution(name)
    files = []
    for entry in distribution.files or ():
        if entry.suffix not in (".py", ".so", ".dylib", ".pyd") and entry.name != "METADATA":
            continue
        path = Path(distribution.locate_file(entry))
        record = dict(path=str(entry), present=path.is_file())
        if record["present"]:
            stat = path.stat()
            record.update(
                sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                bytes=stat.st_size,
                filesystem_change_time=stat.st_ctime,
                change_predates_measurement=stat.st_ctime <= first_measurement,
            )
        files.append(record)
    unchanged = bool(files and all(f["present"] and f["change_predates_measurement"] for f in files))
    return dict(
        version_observed_after_run=distribution.version,
        inferred_measurement_version=distribution.version if unchanged else None,
        inference_supported_by_unchanged_installation=unchanged,
        files=files,
    )


def inventory(directory, output):
    metadata = sorted(directory.glob("*.metadata.json"))
    if not metadata:
        raise ValueError("No measurement metadata to establish the observation window")
    first = min(datetime.datetime.fromisoformat(json.loads(p.read_text())["created_at"]).timestamp() for p in metadata)
    result = dict(
        captured_at=datetime.datetime.now(datetime.UTC).isoformat(),
        capture_timing="after measurement",
        first_measurement=datetime.datetime.fromtimestamp(first, datetime.UTC).isoformat(),
        measurement_metadata_unchanged=True,
        inference_assumption="The installed package and library resolution remained unchanged; this is not direct measurement-time version capture.",
        scope="Python source/native modules and distribution METADATA; generated bytecode caches are excluded.",
        metadata_sha256={p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in metadata},
        packages={name: inventory_distribution(name, first) for name in ("catboost", "lightgbm")},
    )
    output.write_text(json.dumps(result, indent=2) + "\n")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--directory", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    facts = inventory(args.directory, args.output)
    print(
        json.dumps(
            {
                name: {key: value for key, value in item.items() if key != "files"}
                for name, item in facts["packages"].items()
            }
        )
    )
