  if (k == "zaga") p <- c(0.1, 0.3, 0.5, 0.8, 0.99)
  same(lss_quantile(family_object(cs$family), p, cs$params), expected$quantile[[k]],
       paste("quantile", k))
}

# lss_simulate keeps R's random number generators; the Box-Cox families draw
# R uniforms and invert them through the core quantile.
for (k in simulate_cases) {
  cs <- cases[[k]]
  set.seed(848)
  same(lss_simulate(family_object(cs$family), cs$params, n = length(cs$y)),
       expected$simulate[[k]], paste("simulate", k))
}

for (k in names(mean_cases)) {
  same(lss_mean(family_object(k), mean_cases[[k]]), expected$mean[[k]], paste("mean", k))
}
