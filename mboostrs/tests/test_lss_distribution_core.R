# Zeros and infinities must match exactly; other values to 1e-8 relative.
same <- function(new, old, label, tol = 1e-8) {
  if (length(new) != length(old)) {
    stop(sprintf("%s: length %d, expected %d", label, length(new), length(old)))
  }
  exact <- !is.finite(old) | old == 0
  rel <- abs(new[!exact] / old[!exact] - 1)
  if (!all(new[exact] == old[exact]) || any(!is.finite(rel)) || any(rel > tol)) {
    stop(sprintf("%s: differs from the R implementation (max relative %g)",
                 label, if (length(rel)) max(rel) else NA_real_))
  }
}

