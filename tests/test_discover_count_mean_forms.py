"""Count complexity choices use paired core statistics and preserve constraints."""

import importlib

import numpy as np
import polars as pl
import pytest

import mboostrs as mb
from mboostrs import _rust


def test_core_choice_reference_scaling_and_exact_ties():
    simple = np.array([1.0, 2.0, 1.5, 2.2, 1.9])
    rich = np.array([0.9, 2.2, 1.3, 2.3, 1.8])
    difference = simple - rich
    mean = float(difference.mean())
    se = float(difference.std(ddof=1) / len(difference) ** 0.5)
    decision, actual, actual_se = _rust.prefer_simpler_cv(simple, rich, 2.0)
    assert decision == (mean <= 2 * se)
    np.testing.assert_allclose([actual, actual_se], [mean, se], rtol=0, atol=1e-15)
    for scale in (1e-200, 1e200):
        chosen, d, s = _rust.prefer_simpler_cv(simple * scale, rich * scale, 2.0)
        assert chosen == decision
        np.testing.assert_allclose([d / scale, s / scale], [mean, se], rtol=0, atol=1e-14)
    unit = np.ones(5)
    assert _rust.prefer_simpler_cv(unit, unit, 2.0)[0]
    assert not _rust.prefer_simpler_cv(np.nextafter(unit, 2.0), unit, 2.0)[0]


@pytest.mark.parametrize(
    "simple,rich",
    [
        (np.array([1.0]), np.array([1.0])),
        (np.array([1.0, np.nan]), np.array([1.0, 2.0])),
        (np.array([1.0, np.inf]), np.array([1.0, 2.0])),
    ],
)
def test_core_refuses_failed_or_unpaired_fold_evidence(simple, rich):
    with pytest.raises(ValueError):
        _rust.prefer_simpler_cv(simple, rich, 2.0)


def sample(seed=66071, n=180):
    rng = np.random.default_rng(seed)
    x = rng.uniform(-1, 1, n)
    z = rng.uniform(-1, 1, n)
    return pl.DataFrame({"x": x, "z": z, "y": rng.poisson(np.exp(1 + 0.6 * x - 0.4 * z))})


def test_existing_rates_remain_consistent_across_families():
    module = importlib.import_module("mboostrs.discover")
    for family, value in (
        (mb.Gaussian(), 0.1),
        (mb.Poisson(), 0.02),
        (mb.NBinomial(), 0.02),
        (mb.Binomial(), 0.02),
        (mb.GammaReg(), 0.02),
        (mb.GaussReg(), 0.02),
    ):
        assert module._screening_nu(family) == value


def test_count_choice_is_logged_and_can_be_disabled():
    frame = sample()
    automatic = mb.discover(
        frame, "y", family=mb.Poisson(), spread=False, interactions=False, max_mstop=100, seed=66071
    )
    steps = [entry for entry in automatic.log if entry["stage"] == "count mean forms" and "simple_scores" in entry]
    assert steps
    assert len(steps[0]["simple_scores"]) == automatic.folds
    expected = _rust.prefer_simpler_cv(np.asarray(steps[0]["simple_scores"]), np.asarray(steps[0]["rich_scores"]), 2.0)
    assert steps[0]["adopted"] == expected[0]
    original = mb.discover(
        frame,
        "y",
        family=mb.Poisson(),
        spread=False,
        interactions=False,
        simplify_mean=False,
        max_mstop=100,
        seed=66071,
    )
    assert not any(entry["stage"] == "count mean forms" for entry in original.log)
    assert original.provenance["simplify_mean"] is False


def test_mandatory_mean_form_and_budget_refusal():
    frame = sample()
    pinned = mb.discover(
        frame,
        "y",
        family=mb.Poisson(),
        mandatory_terms=["x"],
        spread=False,
        interactions=False,
        max_mstop=100,
        seed=66071,
    )
    steps = [entry for entry in pinned.log if entry["stage"] == "count mean forms" and "simple" in entry]
    assert steps and "bbs(x," in steps[0]["simple"]
    assert "bols(x)" not in steps[0]["simple"]
    limited = mb.discover(
        frame, "y", family=mb.Poisson(), budget_seconds=0, spread=False, interactions=False, seed=66071
    )
    refused = [entry for entry in limited.log if entry["stage"] == "count mean forms"]
    assert refused and any("budget" in entry["reason"] for entry in refused)
    assert not any("simple_scores" in entry for entry in refused)


def test_autogenerated_log_scale_is_preserved():
    rng = np.random.default_rng(66072)
    x = rng.lognormal(0, 1.5, 180)
    frame = pl.DataFrame({"x": x, "y": rng.poisson(np.exp(0.2 + 0.4 * np.log(x)))})
    result = mb.discover(frame, "y", family=mb.Poisson(), spread=False, interactions=False, max_mstop=100, seed=66072)
    steps = [entry for entry in result.log if entry["stage"] == "count mean forms" and "simple" in entry]
    assert steps and "bols(log(x))" in steps[0]["simple"]


def test_gaussian_pipeline_does_not_run_count_shape_selection():
    rng = np.random.default_rng(66073)
    x = rng.uniform(-1, 1, 160)
    result = mb.discover(
        pl.DataFrame({"x": x, "y": np.sin(3 * x) + rng.normal(size=160)}),
        "y",
        family=mb.Gaussian(),
        spread=False,
        interactions=False,
        max_mstop=100,
        seed=66073,
    )
    assert not any(entry["stage"] == "count mean forms" for entry in result.log)
