#!/usr/bin/env python3
"""Generate and check `python/mboostrs/_rust.pyi` against the compiled module.

A type stub that drifts from the extension it describes is worse than no stub:
a type checker reports errors for calls that work and accepts calls that fail
at run time. The hand-written one had drifted both ways -- 22 of 36 registered
symbols had no stub, and 8 stub entries named symbols the module does not
export -- because nothing compared the two.

PyO3 records each function's Python-visible signature in
``__text_signature__``, which is what ``help()`` prints, so the stub can be
derived from the module rather than maintained beside it. Argument *types* are
not in that signature -- PyO3 does not surface them -- so this writes the
argument names with their defaults and annotates the rest as ``Any``. That is
weaker than a hand-written stub at its best and stronger than one that has
gone stale, and the names and arity are the part a caller gets wrong.

Usage::

    python tools/generate_rust_stub.py            # rewrite the stub
    python tools/generate_rust_stub.py --check    # fail if it is out of date
"""
from __future__ import annotations

import argparse
import ast
import inspect
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
STUB = ROOT / "python/mboostrs/_rust.pyi"

HEADER = '''"""Type stubs for the Rust extension module mboostrs._rust.

Generated by tools/generate_rust_stub.py from the compiled module's own
signatures. Do not edit by hand: run the generator, and if a signature here is
wrong, fix the `#[pyfunction]` it came from.

Argument types are `Any` because PyO3 does not surface them in
`__text_signature__`. What this file does pin is the set of symbols and each
one's argument names, arity and defaults, which is what a caller gets wrong.
"""

from typing import Any

'''


def _module():
    sys.path.insert(0, str(ROOT / "python"))
    import mboostrs._rust as module

    return module


def _registered(module) -> dict[str, object]:
    return {
        name: getattr(module, name)
        for name in dir(module)
        if not name.startswith("__")
    }


def _parameters(signature_text: str) -> str:
    """The parameter list from a ``__text_signature__``, annotated as ``Any``.

    ``(x, y, z=None, flag=True)`` becomes ``x: Any, y: Any, z: Any = None,
    flag: Any = True``. Defaults are kept verbatim, so a stub reader sees the
    same value the extension applies.
    """
    inner = signature_text.strip()
    if inner.startswith("(") and inner.endswith(")"):
        inner = inner[1:-1]
    if not inner.strip():
        return ""

    rendered = []
    depth = 0
    current = ""
    for character in inner:
        if character in "([{":
            depth += 1
        elif character in ")]}":
            depth -= 1
        if character == "," and depth == 0:
            rendered.append(current)
            current = ""
            continue
        current += character
    rendered.append(current)

    parts = []
    for raw in rendered:
        piece = raw.strip()
        if not piece or piece in ("/", "*"):
            # Positional-only and keyword-only markers carry through as-is.
            parts.append(piece)
            continue
        if "=" in piece:
            name, default = piece.split("=", 1)
            parts.append(f"{name.strip()}: Any = {default.strip()}")
        else:
            parts.append(f"{piece}: Any")
    return ", ".join(part for part in parts if part)


def _render(module) -> str:
    lines = [HEADER]
    registered = _registered(module)

    classes = {n: o for n, o in registered.items() if isinstance(o, type)}
    functions = {n: o for n, o in registered.items() if n not in classes}

    for name in sorted(classes):
        obj = classes[name]
        doc = (inspect.getdoc(obj) or "").split("\n")[0]
        lines.append(f"class {name}:")
        if doc:
            lines.append(f'    """{doc}"""')
        methods = [
            attribute for attribute in dir(obj)
            if not attribute.startswith("_")
        ]
        if not methods and not doc:
            lines.append("    ...")
        for method in sorted(methods):
            member = getattr(obj, method, None)
            signature = getattr(member, "__text_signature__", None)
            parameters = _parameters(signature) if signature else "*args: Any, **kwargs: Any"
            # PyO3 writes the receiver as `$self`, which is not a Python
            # identifier; the stub needs the ordinary spelling.
            if parameters.startswith("$self: Any, "):
                parameters = "self, " + parameters[len("$self: Any, "):]
            elif parameters.startswith("$self: Any"):
                parameters = "self" + parameters[len("$self: Any"):]
            elif not parameters.startswith("self"):
                parameters = f"self, {parameters}" if parameters else "self"
            lines.append(f"    def {method}({parameters}) -> Any: ...")
        lines.append("")

    for name in sorted(functions):
        obj = functions[name]
        signature = getattr(obj, "__text_signature__", None)
        if signature is None:
            lines.append(f"{name}: Any")
            continue
        lines.append(f"def {name}({_parameters(signature)}) -> Any: ...")

    return "\n".join(lines).rstrip("\n") + "\n"


def _declared(stub_text: str) -> set[str]:
    tree = ast.parse(stub_text)
    names = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(node.name)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    return names


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="fail if the stub is out of date, writing nothing")
    arguments = parser.parse_args()

    module = _module()
    expected = _render(module)

    if not arguments.check:
        STUB.write_text(expected)
        print(f"wrote {STUB.relative_to(ROOT)}: "
              f"{len(_registered(module))} registered symbols")
        return 0

    if not STUB.exists():
        print(f"{STUB.relative_to(ROOT)} does not exist; run this without --check")
        return 1

    actual = STUB.read_text()
    if actual == expected:
        print(f"{STUB.relative_to(ROOT)} is up to date: "
              f"{len(_registered(module))} registered symbols")
        return 0

    registered = set(_registered(module))
    declared = _declared(actual)
    missing = sorted(registered - declared)
    phantom = sorted(declared - registered)

    print(f"{STUB.relative_to(ROOT)} is out of date.")
    if missing:
        print(f"  registered but not declared ({len(missing)}): {missing}")
    if phantom:
        print(f"  declared but not registered ({len(phantom)}): {phantom}")
    if not missing and not phantom:
        print("  the symbol sets agree; a signature differs")
    print("  run: python tools/generate_rust_stub.py")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
