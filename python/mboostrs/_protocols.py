"""What a fitted model is, written down so a checker can hold us to it.

Helpers that take "a fitted model" -- the summary builders, the diagnostics
tables, the model-selection profiles, the plotting entry points -- had no way
to say which members they relied on, so they asked at runtime:
``hasattr(model, "gaic")`` to mean "distributional",
``hasattr(model, "partial_effects")`` to mean "additive",
``not hasattr(model, "_selected")`` to mean "distributional" via a private
attribute. Each of those is a guess about a name, and each one silently
inverts the day the other class grows that name.

Two things replace it, and they do different jobs:

* **Runtime branching** goes through :mod:`mboostrs._dispatch`, whose
  predicates are ``isinstance`` checks against the real classes. That is the
  only form that cannot be fooled by a coincidence of naming.
* **Type annotations** use the protocols here. A function that annotates its
  argument ``BoostModel`` is checked by the type checker against the members
  listed below, so reaching for one that only `LSSModel` has is an error
  before the code runs.

The protocols are also an executable statement of what the three classes
share: `tests/test_model_protocols.py` asserts each class satisfies the ones
it claims, so a member deleted from one class and not the other is a test
failure rather than an `AttributeError` in a helper months later.

`runtime_checkable` is applied so those tests can use ``isinstance``. Do not
use that for dispatch: a runtime protocol check is `hasattr` for every
member, which is the mechanism this module exists to get out of the branching
paths.
"""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable

import numpy as np

__all__ = ["BoostModel", "LSSBoostModel", "StandardBoostModel"]


@runtime_checkable
class BoostModel(Protocol):
    """The surface every fitted mboostrs model has.

    A helper annotated with this works for `glmboost`, `gamboost`,
    `glmboostLSS` and `gamboostLSS` alike. Members whose *shape* differs
    between the standard and distributional classes -- `fitted_` is an array
    on one and a mapping on the other -- are annotated `Any` here, because the
    protocol's job is to say the member exists and takes no arguments, not to
    pretend the two return the same thing.
    """

    # ── stored state, all properties, all read-only ───────────────────
    @property
    def mstop(self) -> Any: ...
    @property
    def control(self) -> tuple: ...
    @property
    def offset(self) -> Any: ...
    @property
    def offset_(self) -> Any: ...
    @property
    def risk_(self) -> np.ndarray: ...
    @property
    def fitted_(self) -> Any: ...
    @property
    def selected(self) -> Any: ...
    @property
    def weights(self) -> np.ndarray: ...
    @property
    def weight_policy(self) -> str: ...

    # ── the fit, evaluated ────────────────────────────────────────────
    def fitted(self, *args, **kwargs) -> Any: ...
    def predict(self, *args, **kwargs) -> Any: ...
    def residuals(self, *args, **kwargs) -> Any: ...
    def coef(self, *args, **kwargs) -> Any: ...
    def logLik(self, *args, **kwargs) -> float: ...

    # ── names ─────────────────────────────────────────────────────────
    def base_learner_names(self, *args, **kwargs) -> Any: ...
    def variable_names(self, *args, **kwargs) -> Any: ...
    def selected_which(self, *args, **kwargs) -> Any: ...
    def varimp(self, *args, **kwargs) -> Any: ...

    # ── what was fitted, and how ──────────────────────────────────────
    def input_weights(self) -> Any: ...
    def model_weights(self) -> np.ndarray: ...
    def weights_note(self) -> str: ...
    def likelihood_contract(self, *args, **kwargs) -> Any: ...
    def parity_notes(self, *args, **kwargs) -> Any: ...
    def execution_report(self) -> Any: ...

    # ── refit and resample ────────────────────────────────────────────
    def update(self, *args, **kwargs) -> Any: ...
    def with_mstop(self, *args, **kwargs) -> Any: ...
    def continue_to(self, *args, **kwargs) -> Any: ...
    def cvrisk(self, *args, **kwargs) -> Any: ...
    def stabsel(self, *args, **kwargs) -> Any: ...
    def profile_mstop(self, *args, **kwargs) -> Any: ...

    # ── reporting ─────────────────────────────────────────────────────
    def summary(self, *args, **kwargs) -> Any: ...
    def path_frame(self, *args, **kwargs) -> Any: ...
    def residual_frame(self, *args, **kwargs) -> Any: ...
    def save(self, *args, **kwargs) -> Any: ...


@runtime_checkable
class StandardBoostModel(BoostModel, Protocol):
    """A single-predictor-scale fit: `glmboost` or `gamboost`.

    One linear predictor, so the design matrix, the hat matrix and the AIC
    that depends on it all exist. These are the two classes the portable
    artifact format supports.
    """

    def aic(self, *args, **kwargs) -> Any: ...
    def hatvalues(self, *args, **kwargs) -> Any: ...
    def confint(self, *args, **kwargs) -> Any: ...
    def extract(self, *args, **kwargs) -> Any: ...
    def model_frame(self, *args, **kwargs) -> Any: ...
    def model_matrix(self, *args, **kwargs) -> Any: ...
    def nuisance(self, *args, **kwargs) -> Any: ...
    def residual_kinds(self, *args, **kwargs) -> Any: ...
    def prediction_contributions(self, *args, **kwargs) -> Any: ...
    def conformal_interval(self, *args, **kwargs) -> Any: ...


@runtime_checkable
class LSSBoostModel(BoostModel, Protocol):
    """A distributional fit: `glmboostLSS` or `gamboostLSS`.

    Every quantity is per distribution parameter, so `param_names` is the key
    set for the mappings the shared members return, and `risk` is the joint
    path, the same as `risk_`; the per-parameter paths are `parameter_risk()`.
    There is no `aic`: the hat
    matrix of a cyclically fitted multi-parameter path is not the hat matrix
    of any one of them, so the information criterion is `gaic`, computed from
    the family's log-likelihood and the summed degrees of freedom.
    """

    @property
    def param_names(self) -> list[str]: ...

    def params(self, *args, **kwargs) -> Any: ...
    @property
    def risk(self) -> np.ndarray: ...
    def gaic(self, *args, **kwargs) -> Any: ...
    def centiles(self, *args, **kwargs) -> Any: ...
    def prediction_interval(self, *args, **kwargs) -> Any: ...
